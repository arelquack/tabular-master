class TextCleaner:
    @staticmethod
    def clean(text: str) -> str:
        if not isinstance(text, str):
            return ""
        text = re.sub(r'<[^>]+>', ' ', text)
        text = re.sub(r'https?://\S+|www\.\S+', ' ', text)
        text = re.sub(r'@\w+', ' ', text)
        text = re.sub(r'(.)\1{2,}', r'\1', text)
        text = text.lower()
        text = re.sub(r'[^a-zA-Z0-9\s.,!?-]', ' ', text)
        text = re.sub(r'\s+', ' ', text).strip()
        return text

